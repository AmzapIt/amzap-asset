BEGIN;

-- Asset Movement is separate from Assignment:
-- - Movement changes the asset's responsible owner, owning department, or
--   current physical location.
-- - Assignment records who is holding the asset and keeps its own snapshots.
CREATE TABLE IF NOT EXISTS public.asset_movements (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asset_id bigint NOT NULL,
  movement_date date NOT NULL DEFAULT ((CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Bangkok')::date),

  from_location_id bigint,
  to_location_id bigint,
  from_department_id bigint,
  to_department_id bigint,
  from_owner_id bigint,
  to_owner_id bigint,

  reason text NOT NULL,
  notes text,
  changed_by_account_id bigint,
  created_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT asset_movements_asset_fkey
    FOREIGN KEY (asset_id) REFERENCES public.assets(id) ON DELETE CASCADE,
  CONSTRAINT asset_movements_from_location_fkey
    FOREIGN KEY (from_location_id) REFERENCES public.locations(id) ON DELETE RESTRICT,
  CONSTRAINT asset_movements_to_location_fkey
    FOREIGN KEY (to_location_id) REFERENCES public.locations(id) ON DELETE RESTRICT,
  CONSTRAINT asset_movements_from_department_fkey
    FOREIGN KEY (from_department_id) REFERENCES public.departments(id) ON DELETE RESTRICT,
  CONSTRAINT asset_movements_to_department_fkey
    FOREIGN KEY (to_department_id) REFERENCES public.departments(id) ON DELETE RESTRICT,
  CONSTRAINT asset_movements_from_owner_fkey
    FOREIGN KEY (from_owner_id) REFERENCES public."user"(id) ON DELETE RESTRICT,
  CONSTRAINT asset_movements_to_owner_fkey
    FOREIGN KEY (to_owner_id) REFERENCES public."user"(id) ON DELETE RESTRICT,
  CONSTRAINT asset_movements_changed_by_account_fkey
    FOREIGN KEY (changed_by_account_id) REFERENCES public.app_accounts(id) ON DELETE SET NULL,

  CONSTRAINT asset_movements_reason_length_check
    CHECK (char_length(btrim(reason)) BETWEEN 1 AND 1000),
  CONSTRAINT asset_movements_notes_length_check
    CHECK (notes IS NULL OR char_length(notes) <= 10000),
  CONSTRAINT asset_movements_has_change_check
    CHECK (
      from_location_id IS DISTINCT FROM to_location_id
      OR from_department_id IS DISTINCT FROM to_department_id
      OR from_owner_id IS DISTINCT FROM to_owner_id
    )
);

CREATE INDEX IF NOT EXISTS idx_asset_movements_asset_date
  ON public.asset_movements (asset_id, movement_date DESC, id DESC);

CREATE INDEX IF NOT EXISTS idx_asset_movements_changed_by
  ON public.asset_movements (changed_by_account_id)
  WHERE changed_by_account_id IS NOT NULL;

COMMENT ON TABLE public.asset_movements IS
  'History of changes to an asset owner, owning department, or physical location.';
COMMENT ON COLUMN public.asset_movements.changed_by_account_id IS
  'Login account in public.app_accounts that performed the movement.';

COMMIT;
