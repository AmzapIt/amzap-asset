BEGIN;

CREATE TABLE IF NOT EXISTS public.employee_offboardings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public."user"(id) ON DELETE RESTRICT,
  started_at timestamptz NOT NULL DEFAULT now(),
  started_by_account_id bigint REFERENCES public.app_accounts(id) ON DELETE SET NULL,
  closed_at timestamptz,
  closed_by_account_id bigint REFERENCES public.app_accounts(id) ON DELETE SET NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS employee_offboardings_one_open_per_user
  ON public.employee_offboardings (user_id) WHERE closed_at IS NULL;
CREATE INDEX IF NOT EXISTS employee_offboardings_user_latest
  ON public.employee_offboardings (user_id, id DESC);

CREATE TABLE IF NOT EXISTS public.employee_offboarding_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  offboarding_id bigint NOT NULL REFERENCES public.employee_offboardings(id) ON DELETE CASCADE,
  item_type text NOT NULL CHECK (item_type IN ('asset', 'accessory')),
  asset_id bigint REFERENCES public.assets(id) ON DELETE RESTRICT,
  assignment_id bigint REFERENCES public.asset_assignments(id) ON DELETE RESTRICT,
  employee_accessory_id bigint REFERENCES public.employee_accessories(id) ON DELETE RESTRICT,
  expected_quantity integer NOT NULL CHECK (expected_quantity > 0),
  returned_quantity_at_start integer NOT NULL DEFAULT 0 CHECK (returned_quantity_at_start >= 0),
  requires_review boolean NOT NULL DEFAULT false,
  resolution text CHECK (resolution IN ('not_held')),
  resolution_reason text,
  resolved_at timestamptz,
  resolved_by_account_id bigint REFERENCES public.app_accounts(id) ON DELETE SET NULL,
  CONSTRAINT employee_offboarding_item_shape CHECK (
    (item_type='asset' AND asset_id IS NOT NULL AND employee_accessory_id IS NULL AND expected_quantity=1)
    OR (item_type='accessory' AND employee_accessory_id IS NOT NULL AND asset_id IS NULL AND assignment_id IS NULL)
  ),
  CONSTRAINT employee_offboarding_resolution_reason CHECK (
    resolution IS NULL OR
    (requires_review AND char_length(btrim(resolution_reason)) BETWEEN 1 AND 1000)
  )
);

CREATE UNIQUE INDEX IF NOT EXISTS employee_offboarding_unique_asset
  ON public.employee_offboarding_items (offboarding_id, asset_id)
  WHERE asset_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS employee_offboarding_unique_accessory
  ON public.employee_offboarding_items (offboarding_id, employee_accessory_id)
  WHERE employee_accessory_id IS NOT NULL;

-- Progress is calculated from actual return records. A transfer or disposal
-- does not make an unreceived item disappear from the offboarding checklist.
CREATE OR REPLACE VIEW public.employee_offboarding_item_progress AS
SELECT
  item.*,
  progress.received_quantity,
  CASE
    WHEN item.resolution='not_held' THEN 0
    ELSE GREATEST(0, item.expected_quantity-progress.received_quantity)
  END AS pending_quantity
FROM public.employee_offboarding_items item
JOIN public.employee_offboardings offboarding ON offboarding.id=item.offboarding_id
LEFT JOIN public.employee_accessories accessory ON accessory.id=item.employee_accessory_id
CROSS JOIN LATERAL (
  SELECT CASE
    WHEN item.item_type='accessory'
      THEN LEAST(item.expected_quantity, GREATEST(0, COALESCE(accessory.returned_quantity,0)-item.returned_quantity_at_start))
    WHEN item.assignment_id IS NOT NULL AND EXISTS (
      SELECT 1 FROM public.asset_stock_receipts receipt
      WHERE receipt.from_assignment_id=item.assignment_id AND receipt.receipt_type='return'
    ) THEN 1
    WHEN item.assignment_id IS NULL AND EXISTS (
      SELECT 1 FROM public.asset_stock_receipts receipt
      WHERE receipt.asset_id=item.asset_id
        AND receipt.receipt_type='return'
        AND receipt.returned_by_user_id=offboarding.user_id
        AND receipt.created_at>=offboarding.started_at
    ) THEN 1
    ELSE 0
  END::integer AS received_quantity
) progress;

COMMIT;
