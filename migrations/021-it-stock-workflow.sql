BEGIN;

-- A physical IT stock location is distinct from the permanent F1/F2 code prefix.
INSERT INTO public.locations (name, is_active)
SELECT 'คลัง IT', true
WHERE NOT EXISTS (
  SELECT 1 FROM public.locations WHERE name = 'คลัง IT'
);

CREATE TABLE IF NOT EXISTS public.asset_inventory_settings (
  singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
  it_stock_location_id bigint NOT NULL REFERENCES public.locations(id) ON DELETE RESTRICT
);

INSERT INTO public.asset_inventory_settings (singleton, it_stock_location_id)
SELECT true, id
FROM public.locations
WHERE name = 'คลัง IT'
ORDER BY id
LIMIT 1
ON CONFLICT (singleton) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.asset_stock_receipts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asset_id bigint NOT NULL REFERENCES public.assets(id) ON DELETE CASCADE,
  receipt_type text NOT NULL CHECK (receipt_type IN ('new', 'return')),
  receipt_date date NOT NULL,
  from_assignment_id bigint REFERENCES public.asset_assignments(id) ON DELETE SET NULL,
  returned_by_user_id bigint REFERENCES public."user"(id) ON DELETE SET NULL,
  asset_condition text NOT NULL CHECK (asset_condition IN ('ready', 'repair')),
  reason text NOT NULL CHECK (char_length(btrim(reason)) BETWEEN 1 AND 1000),
  received_by_account_id bigint REFERENCES public.app_accounts(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_asset_stock_receipts_asset
  ON public.asset_stock_receipts (asset_id, receipt_date DESC, id DESC);

COMMIT;
